class InvalidStartStateError(Exception):
  """Raised when the start state is invalid."""


def _make_pose(position: np.ndarray, rotation: np.ndarray | None) -> np.ndarray:
  """Returns a pose matrix from position and rotation."""
  if len(position.shape) == 1:
    pose = np.eye(4, dtype=position.dtype)
    pose[:3, :3] = rotation
    pose[:3, 3] = position
  else:
    batch_size = position.shape[0]
    pose = np.eye(4, dtype=position.dtype)
    pose = np.tile(pose, (batch_size, 1, 1))
    pose[:, :3, :3] = rotation
    pose[:, :3, 3] = position
  return pose


def _move_robot_along_axis(
    world: mujoco_simulator.MujocoWorld,
    robot_name: str,
    axis: str,
    new_coordinate: float,
) -> None:
  """Moves a robot to a new coordinate along the given axis."""
  transform = world.GetWorldTransform(robot_name)

  if axis == 'x':
    transform[0, 3] = new_coordinate  # Column 3 is translation, 0 is x-axis.
  elif axis == 'y':
    transform[1, 3] = new_coordinate  # Column 3 is translation, 1 is y-axis.
  elif axis == 'z':
    transform[2, 3] = new_coordinate  # Column 3 is translation, 2 is z-axis.
  else:
    raise ValueError(f'Unsupported axis: {axis}')

  world.SetWorldTransform(robot_name, transform)


def _is_monotonically_decreasing(x: Sequence[float]):
  """Returns whether a sequence is monotonically decreasing."""
  for i in range(len(x) - 1):
    if x[i] < x[i + 1]:
      return False
  return True


class Range(struct.PyTreeNode):
  """Represents an arbitrary-dimensional range."""

