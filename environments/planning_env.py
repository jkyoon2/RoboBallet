# How many times to try sampling an obstacle box.
_MAX_OBSTACLE_SAMPLING_ATTEMPTS = 100

# How far targets are offset from surfaces.
_TARGET_SURFACE_OFFSET = 0.03

# The direction the robot is facing in the robot frame.
_ROBOT_FACING_DIRECTION_LOCAL = np.array([1.0, 0.0, 0.0], dtype=np.float32)

# Floating point comparison epsilon.
_EPSILON = 1e-3

_GENERATED_OBSTACLE_COLOUR = np.array([0.4, 0.4, 0.4], dtype=np.float32)

# During obstacle generation, we need to be able to move boxes out of the way.
# This is where "out of the way" is.
_FAR_AWAY = 1000.0


